def active_trajectory(ell: np.ndarray) -> np.ndarray:
    """The drawn auxiliary variable of the active half-space, ell cycles ahead."""
    frequency, phase = ACTIVE_WAVE
    return (ENVELOPE_LEVEL + ENVELOPE_DRIFT * ell
            - ENVELOPE_AMPLITUDE * ENVELOPE_RHO ** ell * np.cos(frequency * ell + phase))


def inactive_trajectory(ell: np.ndarray) -> np.ndarray:
    """The drawn slack of the inactive half-space, ell cycles ahead."""
    frequency, phase = INACTIVE_WAVE
    return (ENVELOPE_FLOOR
            + ENVELOPE_TRANSIENT * ENVELOPE_RHO ** ell * np.cos(frequency * ell + phase))


def envelope_crossings() -> dict:
    """The four marked lookaheads of the envelope figure.

    Returns the zero crossings of the active lower and upper bounds, the first zero of the
    drawn active trajectory, which must lie between them, and the zero crossing of the
    inactive upper bound.
    """
    lower = rigorous_deactivation_horizon(ENVELOPE_LEVEL, ENVELOPE_DRIFT, ENVELOPE_AMPLITUDE,
                                          ENVELOPE_RHO)
    upper = rigorous_deactivation_horizon(ENVELOPE_LEVEL, ENVELOPE_DRIFT, -ENVELOPE_AMPLITUDE,
                                          ENVELOPE_RHO)
    # The trajectory's first zero is bracketed on a fine grid and then bisected
    grid = np.linspace(0.0, 21.0, 21001)
    first = int(np.argmax(active_trajectory(grid) <= 0.0))
    low, high = grid[first - 1], grid[first]
    for _ in range(60):
        middle = 0.5 * (low + high)
        low, high = (middle, high) if active_trajectory(middle) > 0.0 else (low, middle)
