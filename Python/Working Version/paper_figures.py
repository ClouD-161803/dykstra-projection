def error_curves(num_planes: int, num_dimensions: int, index: int, cycles: int) -> dict:
    """Squared errors of Dykstra and the accelerated solver on one problem of a size tier.

    Returns both error histories, the cycle and certificate of the accelerated solver's
    settlement, the first cycle at which each history is within PERFORMANCE_TOLERANCE, and
    the largest differences between the two runs before the settlement, in squared error
    and in the infinity norm of the iterates at the cycle ends, which are zero up to rounding
    when the accelerated solver follows Dykstra's path, and the distance between its
    certified point and the quadprog projection.
    """
    A, b, z = problem(num_planes, num_dimensions, problem_seed(num_planes, index))
    runs = {}
    for name, solver_type in (("Dykstra", DykstraProjectionSolver),
                              ("accelerated", LTIVer5Solver)):
        solver = solver_type(z, A, b, cycles, track_error=True,
                             min_error=PERFORMANCE_TOLERANCE, dimensions=num_dimensions)
        result = solver.solve()
        runs[name] = (np.asarray(result.squared_errors, dtype=float), result, solver)

    dykstra, accelerated = runs["Dykstra"][0], runs["accelerated"][0]
    result, solver = runs["accelerated"][1], runs["accelerated"][2]
    settle = result.settled_at
    before = settle if settle is not None else cycles + 1

    def first_within(errors: np.ndarray) -> int | None:
        reached = np.flatnonzero(errors <= PERFORMANCE_TOLERANCE)
        return int(reached[0]) if reached.size else None

    return {
        "dykstra": dykstra, "accelerated": accelerated,
        "settle": settle, "certificate": result.certificate,
        "first_dykstra": first_within(dykstra), "first_accelerated": first_within(accelerated),
        "error_difference": float(np.max(np.abs(dykstra[:before] - accelerated[:before]))),
        "path_difference": float(np.max(np.abs(runs["Dykstra"][1].path[:before, -1]
                                               - result.path[:before, -1]))),
        "projection_error": (float(np.linalg.norm(result.projection - solver.actual_projection))
                             if settle is not None else None),
    }


def thinned_cycles(curves: dict, cycles: int) -> np.ndarray:
    """The cycles at which the performance figure samples its curves.

    These are PERFORMANCE_POINTS + 1 evenly spaced cycles, every turning point of either
    curve before the settlement, the first cycle within the tolerance of either, and the
    settlement with the cycle before it, so that the drop is drawn vertically.
    """
    keep = set(np.rint(np.linspace(0, cycles, PERFORMANCE_POINTS + 1)).astype(int).tolist())
    settle = curves["settle"]
    end = settle if settle is not None else cycles + 1
    for errors in (curves["dykstra"], curves["accelerated"][:end]):
        steps = np.sign(np.diff(errors))
        moving = np.flatnonzero(steps)
        turns = moving[1:][steps[moving[1:]] != steps[moving[:-1]]]
        keep.update(turns.tolist())
    for cycle in (curves["first_dykstra"], curves["first_accelerated"]):
        if cycle is not None:
            keep.add(cycle)
    if settle is not None:
        keep.update((settle - 1, settle))
    return np.array(sorted(c for c in keep if 0 <= c <= cycles))


def performance_error_pgfplots(curves: dict, cycles: int) -> str:
    """The left panel of fig:performance as pgfplots, without the right panel."""
    sample = thinned_cycles(curves, cycles)

    def coordinates(errors: np.ndarray) -> str:
        return " ".join(f"({c},{max(errors[c], PERFORMANCE_FLOOR):.4g})" for c in sample)

    settle = curves["settle"]
    settle_lines = ""
    if curves["certificate"] == "kkt":
        settle_lines = (
            f"      \\draw[figred, dotted] (axis cs:{settle},1e-10) -- (axis cs:{settle},1e2);\n"
            f"      \\node[figred, font=\\scriptsize, anchor=west] at (axis cs:{settle},3e-9) "
            f"{{\\ settle ({settle})}};\n")
    return rf"""  \begin{{tikzpicture}}
    \begin{{axis}}[paperaxis, width=0.47\linewidth, height=0.40\linewidth,
                 ymode=log, xmin=0, xmax={cycles}, ymin=1e-10, ymax=1e2,
                 xlabel={{cycle $t$}}, ylabel={{squared error}},
                 legend pos=north east]
      \addplot[figink, thick] coordinates {{{coordinates(curves["dykstra"])}}};
      \addlegendentry{{Dykstra}}
      \addplot[figred, thick] coordinates {{{coordinates(curves["accelerated"])}}};
      \addlegendentry{{accelerated}}
      \addplot[figgrey, dashed, forget plot] coordinates {{(0,1e-3) ({cycles},1e-3)}};
{settle_lines}      \node[figgrey, font=\scriptsize, anchor=south east] at (axis cs:{cycles},1.4e-3) {{tolerance $10^{{-3}}$}};
    \end{{axis}}
  \end{{tikzpicture}}%
"""


def performance_error_figure(index: int = PERFORMANCE_INDEX,
                             cycles: int = PERFORMANCE_CYCLES) -> dict:
    """Draw squared error against cycle on one problem and return the curves."""
    num_planes, num_dimensions = PERFORMANCE_SIZE
    curves = error_curves(num_planes, num_dimensions, index, cycles)

    fig, ax = plt.subplots(figsize=(6.2, 4.4))
    for name, key, colour, width in (("Dykstra", "dykstra", INK, 2.4),
                                     ("accelerated", "accelerated", RED, 1.8)):
        errors = curves[key]
        # A settled error is rounding noise, drawn at PERFORMANCE_FLOOR to stay on the log axis
        ax.semilogy(np.arange(len(errors)), np.maximum(errors, PERFORMANCE_FLOOR),
                    color=colour, lw=width, label=name)
    ax.axhline(PERFORMANCE_TOLERANCE, color=GREY, lw=1.0, ls="--",
               label=r"tolerance $10^{-3}$")

    # The accelerated solver certifies the projection and holds it from there
    if curves["certificate"] == "kkt":
        settle = curves["settle"]
        ax.axvline(settle, color=RED, lw=0.9, ls=":")
        ax.text(settle, 2.0 * PERFORMANCE_FLOOR, f"  settle ({settle})", color=RED,
                fontsize=9, ha="left")

    ax.set_xlabel("cycle $t$")
    ax.set_ylabel("squared error")
    ax.set_xlim(0, cycles)
    ax.set_ylim(bottom=0.5 * PERFORMANCE_FLOOR)
    ax.legend(fontsize=9, frameon=False, loc="upper right")
    style_axes(ax)
    fig.tight_layout()
    save_figure(fig, "performance_error")

    seed = problem_seed(num_planes, index)
    print(f"  {num_planes} x {num_dimensions}, seed {seed}, {cycles} cycles: squared error "
          f"{curves['dykstra'][0]:.4g} at cycle 0, Dykstra {curves['dykstra'][-1]:.4g} at "
          f"cycle {cycles}")
    print(f"  first cycle within {PERFORMANCE_TOLERANCE:g}: Dykstra {curves['first_dykstra']}, "
          f"accelerated {curves['first_accelerated']}")
    print(f"  accelerated settles at cycle {curves['settle']} ({curves['certificate']}), "
          f"largest difference before it {curves['error_difference']:.3g} in squared error "
          f"and {curves['path_difference']:.3g} in the iterates, distance of the certified "
          f"point from quadprog {curves['projection_error']}")
    return curves


def performance_seed_summary(indices: range = range(5), cycles: int = 20000) -> list[dict]:
    """The settlement and tolerance cycles of several problems of the performance tier."""
    num_planes, num_dimensions = PERFORMANCE_SIZE
    rows = []
    print(f"  {num_planes} x {num_dimensions} problems under a {cycles}-cycle budget:")
    for index in indices:
        curves = error_curves(num_planes, num_dimensions, index, cycles)
        rows.append({"index": index, "seed": problem_seed(num_planes, index),
                     **{key: curves[key] for key in ("settle", "certificate", "first_dykstra",
                                                     "first_accelerated", "error_difference",
                                                     "path_difference", "projection_error")}})
        row = rows[-1]
        print(f"    index {index} (seed {row['seed']}): settles at {row['settle']} "
              f"({row['certificate']}), within {PERFORMANCE_TOLERANCE:g} at Dykstra "
              f"{row['first_dykstra']}, accelerated {row['first_accelerated']}, largest "
              f"difference before the settlement {row['error_difference']:.3g} in squared "
              f"error and {row['path_difference']:.3g} in the iterates, distance from "
              f"quadprog {row['projection_error']}", flush=True)
    return rows


def run(quick: bool = False) -> None:
    """Rebuild every figure and the LaTeX of those the paper draws inline."""
    quiet_accelerate_warnings()
    cycles = QUICK_CYCLES if quick else PERFORMANCE_CYCLES
    save_tex(vertex_corner_tikz(vertex_gamma_corner_figure()), "fig-vertexcorner")
    save_tex(triple_loop_drift_pgfplots(triple_loop_drift_figure()), "fig-ykdrift")
    save_tex(envelope_bounds_pgfplots(envelope_bounds_figure()), "fig-envelopes")
    save_tex(performance_error_pgfplots(performance_error_figure(cycles=cycles), cycles),
             "fig-performance-left")
    if quick:
        performance_seed_summary(QUICK_INDICES, QUICK_CYCLES)
    else:
        performance_seed_summary()
    print(f"Finished: vertex_gamma_corner, triple_loop_drift, envelope_bounds and "
          f"performance_error as PNG and PDF, and their fig-*.tex files, in {OUTPUT_DIR}")


def main() -> None:
    """Parse the command line and run."""
    global OUTPUT_DIR
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--quick", action="store_true",
                        help="a short performance figure written to a temporary directory")
    args = parser.parse_args()
    if args.quick:
        OUTPUT_DIR = tempfile.mkdtemp(prefix="paper_figures_")
    run(args.quick)


if __name__ == "__main__":
    main()
