def quiet_accelerate_warnings() -> None:
    """Silence the matmul warnings numpy 2.1 raises with Apple's Accelerate library."""
    # Accelerate leaves floating-point exception flags set after finite products, and
    # numpy reports them as divide-by-zero, overflow and invalid-value warnings
    warnings.filterwarnings("ignore", message=r".* encountered in matmul",
                            category=RuntimeWarning)


def save_figure(fig: Figure, name: str) -> None:
    """Write a figure as PNG and PDF."""
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    path = os.path.join(OUTPUT_DIR, name)
    fig.savefig(path + ".png", dpi=130, bbox_inches="tight")
    fig.savefig(path + ".pdf", bbox_inches="tight")
    plt.close(fig)
    print(f"Wrote {path}.png and {path}.pdf")


def save_tex(text: str, name: str, command: str = "python paper_figures.py") -> str:
    """Write LaTeX for the paper, headed by the command that produced it, and return the path."""
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    path = os.path.join(OUTPUT_DIR, name + ".tex")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(f"% generated by `{command}` in Python/Working Version of "
                     "github.com/ClouD-161803/dykstra-projection\n")
        handle.write(text)
    print(f"Wrote {path}")
    return path


def tex_number(value: float, decimals: int = 4) -> str:
    """A number rounded to decimals places, with trailing zeros dropped."""
    text = f"{value:.{decimals}f}".rstrip("0").rstrip(".")
