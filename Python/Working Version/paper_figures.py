def triple_loop_drift_data() -> dict:
    """The stored scalars of the full-activity phase and their drift lines.

    Returns the scalars at every cycle, the residuals r_i, the cycle at which the scalar of
    half-space 3 reaches zero, and the drift lines y_i at cycle 1 plus (t - 1) r_i for t from
    0 to two cycles past that one.
    """
    A, b, _, residuals = three_plane_arrangement()
    history = phase_scalars(A, b, np.array(DRIFT_ENTRY_STATE), np.array(DRIFT_ENTRY_SCALARS),
                            DRIFT_CYCLES)
    # The phase ends when the draining scalar of half-space 3 reaches zero
    shed = int(np.argmax(history[:, 2] <= 1e-12))
    drift_cycles = np.arange(0, shed + 3)
    drift = history[1][None, :] + (drift_cycles[:, None] - 1) * residuals[None, :]
    return {"history": history, "residuals": residuals, "shed": shed,
            "drift_cycles": drift_cycles, "drift": drift}


